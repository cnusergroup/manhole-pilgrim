"""Generate demo narration with Amazon Polly, plus subtitles and a CapCut (剪映) script.

Input : video/narration.json
Output: video/voice/<id>.mp3          one clip per segment (Amazon Polly, generative engine)
        web/demo_timing.js            per-segment durations, read by web/demo.js so visuals follow the voice
        video/narration.srt           subtitles (timeline = voice clips + gaps, same as demo.js)
        video/capcut_script.txt       plain script for CapCut "文本朗读" if you'd rather voice it there

Usage: python scripts/make_voice.py          (re-run after editing narration.json)
"""
import json
import pathlib
import re
import subprocess

import boto3

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "video" / "narration.json"
VOICE = ROOT / "video" / "voice"
GAP = 0.45      # 段落之间的停顿（秒），demo.js 使用同一个值
LEAD_IN = 1.0   # 视频开头到第一句的时间


def duration(path: pathlib.Path) -> float:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
                         capture_output=True, text=True, check=True).stdout
    return float(out.strip())


def srt_time(t: float) -> str:
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def main() -> None:
    cfg = json.loads(SRC.read_text(encoding="utf-8"))
    v = cfg["voice"]
    polly = boto3.client("polly", region_name=v["region"])
    VOICE.mkdir(parents=True, exist_ok=True)

    timing, srt, t = {}, [], LEAD_IN
    for i, seg in enumerate(cfg["segments"], 1):
        mp3 = VOICE / f"{seg['id']}.mp3"
        stamp = VOICE / f"{seg['id']}.txt"
        if not (mp3.exists() and stamp.exists() and stamp.read_text(encoding="utf-8") == seg["text"] + v["voice_id"]):
            r = polly.synthesize_speech(Engine=v["engine"], VoiceId=v["voice_id"], OutputFormat="mp3",
                                        SampleRate="24000", Text=seg["text"])
            mp3.write_bytes(r["AudioStream"].read())
            stamp.write_text(seg["text"] + v["voice_id"], encoding="utf-8")
        d = duration(mp3)
        timing[seg["id"]] = round(d, 3)
        srt.append(f"{i}\n{srt_time(t)} --> {srt_time(t + d)}\n{seg['text']}\n")
        print(f"{seg['id']}  {d:5.2f}s  @ {t:6.2f}s  {seg['scene']}")
        t += d + GAP

    seg_list = [{"id": s["id"], "scene": s["scene"], "caption": s.get("caption", "")} for s in cfg["segments"]]
    (ROOT / "web" / "demo_timing.js").write_text(
        "// Generated by scripts/make_voice.py from video/narration.json. Do not edit by hand.\n"
        "window.MP_DEMO_TIMING = "
        + json.dumps({"gap": GAP, "leadIn": LEAD_IN, "segments": timing, "list": seg_list}, ensure_ascii=False)
        + ";\n",
        encoding="utf-8")
    (ROOT / "video" / "narration.srt").write_text("\n".join(srt), encoding="utf-8")
    # 网站内预览（?demo=1&voice=1）用的配音副本
    web_voice = ROOT / "web" / "demo_voice"
    web_voice.mkdir(exist_ok=True)
    for seg in cfg["segments"]:
        (web_voice / f"{seg['id']}.mp3").write_bytes((VOICE / f"{seg['id']}.mp3").read_bytes())

    # 剪映配音稿：一段一行，可直接粘贴进「文本」→「文本朗读」，或导入 SRT 后批量朗读
    lines = [
        "Manhole Pilgrim 蓋めぐり — 演示视频旁白稿（英文配音）",
        "用法 A：剪映 → 导入 narration.srt 作为字幕 → 全选字幕 → 文本朗读，选英文男声。",
        "用法 B：逐段复制下面的文字到剪映「文本朗读」。段落之间留约 0.5 秒停顿。",
        f"预计总时长：{t - GAP:.0f} 秒",
        "",
    ]
    for seg in cfg["segments"]:
        lines.append(f"[{seg['id']} · {seg['scene']} · {timing[seg['id']]:.1f}s]")
        lines.append(seg["text"])
        lines.append("")
    (ROOT / "video" / "capcut_script.txt").write_text("\n".join(lines), encoding="utf-8")
    print(f"total narration timeline: {t - GAP:.1f}s")


if __name__ == "__main__":
    main()
